window.ayahUrls = function (ref) {
  const r = window.AYAT[ref];
  if (!r) return [];
  const [s, from, to = from] = r;
  let base = 0;
  for (let i = 0; i < s - 1; i++) base += window.SURAH_AYAHS[i];
  const out = [];
  for (let a = from; a <= to; a++) out.push(`https://cdn.islamic.network/quran/audio/128/ar.alafasy/${base + a}.mp3`);
  return out;
};
